// Command surface writes docs/port/SURFACE.md: every exported method on every
// Wails-bound service type — the attack surface the page can call — with the
// renderer channel it serves.
//
// A bound type is any type under internal/ whose name is `Service`, ends in
// `Service`, or is `GitService`. Each exported method must carry a
// `// channel: <ipc channel>` or `// gitsvc: <method>` line in its doc comment;
// Wails lifecycle hooks (ServiceStartup, ServiceShutdown, ServiceName,
// ServeHTTP) are exempt. With -check, an untagged method fails the run.
//
// Usage: go run ./scripts/port/surface [-check]
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type method struct {
	pkg, typ, name, sig, tag, pos string
}

var lifecycle = map[string]bool{"ServiceStartup": true, "ServiceShutdown": true, "ServiceName": true, "ServeHTTP": true}

func isBound(name string) bool {
	return name == "Service" || strings.HasSuffix(name, "Service")
}

func main() {
	check := flag.Bool("check", false, "fail when a bound method has no channel tag")
	flag.Parse()
	root := "."
	fset := token.NewFileSet()
	var out []method
	err := filepath.WalkDir(filepath.Join(root, "internal"), func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && (d.Name() == "testdata") {
			return filepath.SkipDir
		}
		if d.IsDir() || !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "_test.go") {
			return nil
		}
		f, err := parser.ParseFile(fset, p, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv == nil || !fn.Name.IsExported() || lifecycle[fn.Name.Name] {
				continue
			}
			recv := fn.Recv.List[0].Type
			if star, ok := recv.(*ast.StarExpr); ok {
				recv = star.X
			}
			if g, ok := recv.(*ast.IndexExpr); ok {
				recv = g.X
			}
			id, ok := recv.(*ast.Ident)
			if !ok || !isBound(id.Name) {
				continue
			}
			m := method{pkg: f.Name.Name, typ: id.Name, name: fn.Name.Name, pos: fmt.Sprintf("%s:%d", filepath.ToSlash(p), fset.Position(fn.Pos()).Line)}
			if fn.Doc != nil {
				for _, c := range fn.Doc.List {
					t := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
					if strings.HasPrefix(t, "channel:") || strings.HasPrefix(t, "gitsvc:") {
						m.tag = t
					}
				}
			}
			m.sig = signature(fn)
			out = append(out, m)
		}
		return nil
	})
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	sort.Slice(out, func(i, j int) bool {
		a, b := out[i], out[j]
		if a.pkg+a.typ != b.pkg+b.typ {
			return a.pkg+a.typ < b.pkg+b.typ
		}
		return a.name < b.name
	})
	var b strings.Builder
	untagged := 0
	b.WriteString("# Bound surface\n\nEvery exported method on a Wails-bound service: the page (and any script running in it) can call\n")
	b.WriteString("each one. Generated by `go run ./scripts/port/surface`; `-check` fails on an untagged method.\n\n")
	fmt.Fprintf(&b, "%d methods.\n\n| service | method | serves | params | source |\n|---|---|---|---|---|\n", len(out))
	for _, m := range out {
		tag := m.tag
		if tag == "" {
			tag = "**UNTAGGED**"
			untagged++
		}
		fmt.Fprintf(&b, "| %s.%s | %s | %s | `%s` | %s |\n", m.pkg, m.typ, m.name, tag, m.sig, m.pos)
	}
	if err := os.WriteFile(filepath.Join(root, "docs/port/SURFACE.md"), []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("SURFACE: %d bound methods, %d untagged\n", len(out), untagged)
	if *check && untagged > 0 {
		os.Exit(1)
	}
}

func signature(fn *ast.FuncDecl) string {
	var parts []string
	for _, p := range fn.Type.Params.List {
		t := exprString(p.Type)
		if len(p.Names) == 0 {
			parts = append(parts, t)
		}
		for _, n := range p.Names {
			parts = append(parts, n.Name+" "+t)
		}
	}
	return "(" + strings.Join(parts, ", ") + ")"
}

func exprString(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return "*" + exprString(t.X)
	case *ast.SelectorExpr:
		return exprString(t.X) + "." + t.Sel.Name
	case *ast.ArrayType:
		return "[]" + exprString(t.Elt)
	case *ast.MapType:
		return "map[" + exprString(t.Key) + "]" + exprString(t.Value)
	case *ast.Ellipsis:
		return "..." + exprString(t.Elt)
	case *ast.InterfaceType:
		return "any"
	case *ast.FuncType:
		return "func"
	default:
		return fmt.Sprintf("%T", e)
	}
}
