#!/usr/bin/env node
// Builds docs/port/TEST-MAP.md: every vitest case that existed before the port,
// and where it lives now. The baseline list comes from a vitest JSON report
// (docs/port/baseline-tests.json, captured once at M0), so a case that silently
// disappears from the suite still has a row here and must be accounted for.
//
// Usage: node scripts/port/testmap.mjs [--baseline <vitest-json>]
// Re-running keeps the "new home" and "note" columns already written in
// TEST-MAP.md, keyed by file + full test name.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, relative } from 'node:path'

const root = resolve(import.meta.dirname, '../..')
const out = resolve(root, 'docs/port/TEST-MAP.md')
const argIdx = process.argv.indexOf('--baseline')
const baselinePath = resolve(root, argIdx > 0 ? process.argv[argIdx + 1] : 'docs/port/baseline-tests.json')

const report = JSON.parse(readFileSync(baselinePath, 'utf8'))

// Which src/main modules a test file imports decides its default destination:
// a file that never touches the main process keeps running in vitest unchanged.
function mainImports(file) {
  try {
    const src = readFileSync(resolve(root, file), 'utf8')
    return [...new Set([...src.matchAll(/from '\.\.\/src\/main\/([A-Za-z]+)'/g)].map((m) => m[1]))].sort()
  } catch {
    return []
  }
}

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')

const existing = new Map()
if (existsSync(out)) {
  for (const line of readFileSync(out, 'utf8').split('\n')) {
    const cells = line.split(/(?<!\\)\|/).map((c) => c.trim())
    // | file | test | new home | note |
    if (cells.length >= 6 && cells[1] && cells[1] !== 'file' && !cells[1].startsWith('---')) {
      existing.set(`${cells[1]}\u0000${cells[2]}`, { home: cells[3], note: cells[4] })
    }
  }
}

const rows = []
for (const file of report.testResults) {
  const rel = relative(root, file.name)
  const mods = mainImports(rel)
  const fallback = mods.length ? `todo → Go (${mods.join(', ')})` : 'still in vitest'
  for (const a of file.assertionResults) {
    const name = esc(a.fullName)
    const prev = existing.get(`${rel}\u0000${name}`)
    rows.push({ file: rel, name, home: prev?.home || fallback, note: prev?.note ?? (a.status === 'skipped' || a.status === 'pending' ? 'skipped at baseline' : '') })
  }
}

const todo = rows.filter((r) => r.home.startsWith('todo')).length
const header = `# Test map

Every vitest case from the pre-port baseline (${report.numTotalTests} tests in ${report.testResults.length} files,
${report.numPassedTests} passing, ${report.numPendingTests} skipped) and where it lives now. Generated by
\`node scripts/port/testmap.mjs\`; the "new home" and "note" columns survive regeneration.

- \`still in vitest\` — the test's subject stayed in TypeScript; it runs unchanged.
- \`Go: <package>.<TestName>\` — ported; the Go test covers the same case.
- \`deleted\` — the subject no longer exists; the note says why.
- \`todo → Go (…)\` — not ported yet.

Open rows: **${todo}** of ${rows.length}.

| file | test | new home | note |
|------|------|----------|------|
`
writeFileSync(out, header + rows.map((r) => `| ${r.file} | ${r.name} | ${r.home} | ${r.note} |`).join('\n') + '\n')
console.log(`TEST-MAP: ${rows.length} rows, ${todo} open`)
